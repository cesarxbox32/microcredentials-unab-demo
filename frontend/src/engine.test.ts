import {describe,expect,it} from 'vitest'
import {accept,advance,compare,complete,create,defaults,exportCsv,importCsv,loadState,metrics,rotate} from './engine'

describe('License Rotation Engine',()=>{
  it('registra 500 estudiantes y respeta 200 cupos iniciales',()=>{
    const s=create()
    expect(s.students).toHaveLength(500)
    expect(metrics(s)).toMatchObject({used:200,waiting:300,coverage:200})
    expect(s.cohorts.map(c=>c.seats)).toEqual([200,200,100])
  })
  it('libera un cupo solo tras certificación y lo reasigna en FIFO',()=>{
    const s=create()
    complete(s,1)
    rotate(s)
    expect(s.transfers).toBe(0)
    advance(s,1)
    expect(s.transfers).toBe(1)
    expect(s.licenses[0].student).toBe(201)
    expect(s.students[0].status).toBe('Finalizado')
    const count=s.events.length
    rotate(s)
    expect(s.events).toHaveLength(count)
    expect(new Set(s.licenses.map(l=>l.student)).size).toBe(200)
  })
  it('espera al cierre académico de cada tramo y alcanza 500 certificados',()=>{
    const s=create({...defaults,strategy:'cohort'})
    complete(s,199)
    advance(s,1)
    expect(s.transfers).toBe(0)
    complete(s,1)
    advance(s,1)
    expect(s.transfers).toBe(200)
    advance(s,200)
    expect(metrics(s)).toMatchObject({coverage:500,certified:500,waiting:0})
    expect(s.transfers).toBe(300)
  })
  it('detiene el escenario de 10% tras 20 transferencias',()=>{
    const s=create({...defaults,percent:10})
    advance(s,300)
    expect(s.transfers).toBe(20)
    expect(metrics(s)).toMatchObject({coverage:220,waiting:280,remaining:0})
    expect(s.alert).toContain('contractual')
  })
  it('reserva las invitaciones y detecta falta de aceptación',()=>{
    const s=create({...defaults,autoAccept:false})
    advance(s,8)
    expect(metrics(s)).toMatchObject({coverage:0,used:200,waiting:300})
    expect(s.notices.some(n=>n.title==='Invitación no aceptada')).toBe(true)
    accept(s,s.students[0])
    expect(metrics(s).active).toBe(1)
  })
  it('aplica período de gracia y aprobación',()=>{
    const s=create({...defaults,grace:2,approval:true})
    complete(s,1)
    advance(s,2)
    rotate(s,true)
    expect(s.transfers).toBe(0)
    advance(s,1)
    expect(s.transfers).toBe(0)
    rotate(s,true)
    expect(s.transfers).toBe(1)
  })
  it('importa CSV con comillas, deduplica y protege la exportación',()=>{
    const s=create()
    expect(importCsv(s,'nombre,correo\n"Ana, Ejemplo",ana@unab.example\nOtro,ana@unab.example\nFuera,ana@example.com')).toBe(1)
    expect(s.students.at(-1)?.name).toBe('Ana, Ejemplo')
    expect(exportCsv([{nombre:'=1+2'}])).toContain("'=1+2")
  })
  it('recupera la persistencia y restaura datos ante caché ilegible',()=>{
    const s=create()
    advance(s,4)
    expect(loadState({getItem:()=>JSON.stringify(s)})).toEqual(JSON.parse(JSON.stringify(s)))
    expect(loadState({getItem:()=>'{'}).day).toBe(0)
  })
  it('calcula la comparación con tres ejecuciones independientes',()=>{
    const rows=compare(defaults)
    expect(rows).toHaveLength(3)
    expect(rows.every(r=>r.coverage===500&&r.certified===500)).toBe(true)
    expect(rows[0].manual).toBe(9)
    expect(rows[2].wait).toBeLessThan(rows[0].wait)
  })
})

it('mantiene invariantes con 5.000 estudiantes y 1.000 licencias',()=>{
  const s=create({...defaults,count:5000,capacity:1000,strategy:'cohort',duration:30,percent:400,maxTransfers:4000})
  advance(s,180)
  expect(metrics(s)).toMatchObject({coverage:5000,certified:5000,waiting:0})
  expect(s.transfers).toBe(4000)
  expect(s.history.every(point=>point.used<=1000)).toBe(true)
})
